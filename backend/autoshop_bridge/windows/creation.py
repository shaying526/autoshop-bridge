"""Narrow LiteST creation via the observed, already-open AutoShop dialog.

No new native container or HCP data is generated by this module. AutoShop owns
creation and serialization. An empty newly created ST is only initialized via
its verified empty editor, with another backup before the first source save.
"""

import ctypes
import json
import re
import subprocess
import time
from pathlib import Path

from autoshop_bridge.errors import BridgeError, ConflictError
from autoshop_bridge.formats.st import validate_program_edit
from autoshop_bridge.formats.native import parse
from autoshop_bridge.projects.inventory import (
    bounded_read,
    member_path,
    registration,
    select_project,
    unpack_mirror,
    scan,
)
from autoshop_bridge.storage import (
    create_backup,
    native_file,
    regular_file,
    sha256,
    target_lock,
    writable_target,
    write_json_new,
    write_new,
)
from autoshop_bridge.formats.tables import identifier

PROFILE = "autoshop-4.11.0.5-open-new-litest-dialog"
LANGUAGES = ["梯形图(LD)", "结构化文本(LiteST)"]
NATIVE_SUFFIXES = {".st", ".fb", ".stru", ".gvt"}


def digest_dialog(state):
    return sha256(json.dumps(state, sort_keys=True, ensure_ascii=True).encode("ascii"))


def validate_name(name):
    reserved = {"MAIN", "CON", "PRN", "AUX", "NUL"}
    reserved.update(
        "{}{}".format(prefix, n) for prefix in ("COM", "LPT") for n in range(1, 10)
    )
    # Observed AutoShop adds SBR_; keep the full identifier within 63 bytes.
    if (
        not isinstance(name, str)
        or not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]{0,58}", name)
        or not identifier(name)
        or name.upper() in reserved
    ):
        raise BridgeError(
            "ST dialog name must be 1..59 ASCII identifier characters; reserved names are blocked."
        )
    return "SBR_" + name


def mirror_state(project):
    hcp = select_project(project)
    mirror = regular_file(hcp.with_suffix(".hcpp"))
    raw = bounded_read(mirror)
    from autoshop_bridge.projects.registration_baseline import registration_for
    qualified = registration_for(hcp)
    if qualified is not None:
        from autoshop_bridge.projects.inventory import unpack_mirror_evidence
        members, diagnostic = unpack_mirror_evidence(raw)
        saved_hcp, source = qualified
        root = registration(saved_hcp)
        matched, native = {}, {}
        for node in root.findall('file'):
            name = node.findtext('FileName') or ''
            if not name:
                continue
            path = project.joinpath(*member_path(name))
            if path.exists():
                path = regular_file(path)
                if project not in path.parents:
                    raise BridgeError('Registered path leaves the selected project.')
                matched[name] = sha256(bounded_read(path))
        for path in project.iterdir():
            if path.suffix.lower() in NATIVE_SUFFIXES:
                native[path.name] = sha256(bounded_read(native_file(path)))
        native.update({name: value for name, value in matched.items() if Path(name).suffix.lower() in NATIVE_SUFFIXES})
        return dict(hcp=hcp, mirror=mirror, raw=raw, saved_hcp=saved_hcp,
                    matched=matched, native=native, direct_hcp_verified=False,
                    root=root, registration_source=source, mirror_diagnostic=diagnostic)
    members = unpack_mirror(raw)
    keys = [name for name in members if name.casefold() == hcp.name.casefold()]
    if len(keys) != 1:
        raise BridgeError("HCPP must contain one matching HCP registration.")
    saved_hcp = members[keys[0]]
    root = registration(saved_hcp)
    direct = False
    try:
        current_hcp = bounded_read(hcp)
    except PermissionError:
        pass  # A saved mirror is explicitly reported, never called a direct HCP backup.
    else:
        if current_hcp != saved_hcp:
            raise ConflictError(
                "HCP differs from its mirror; save/compile and inspect before creation."
            )
        direct = True
    matched = {}
    for name, content in members.items():
        if name == keys[0]:
            continue
        path = regular_file(project.joinpath(*member_path(name)))
        if project not in path.parents or bounded_read(path) != content:
            raise ConflictError(
                "Mirror member differs from the current project: {}.".format(name)
            )
        matched[name] = sha256(content)
    native = {}
    for path in project.iterdir():
        if path.suffix.lower() in NATIVE_SUFFIXES:
            native[path.name] = sha256(bounded_read(native_file(path)))
    for name in matched:
        if Path(name).suffix.lower() in NATIVE_SUFFIXES:
            native[name] = matched[name]
    return dict(
        hcp=hcp,
        mirror=mirror,
        raw=raw,
        saved_hcp=saved_hcp,
        matched=matched,
        native=native,
        direct_hcp_verified=direct,
        root=root,
    )


def assert_old_native(project, hashes, allowed_new=()):
    for name, expected in hashes.items():
        path = native_file(project.joinpath(*member_path(name)))
        if sha256(bounded_read(path)) != expected:
            raise ConflictError("An existing native file changed: {}.".format(name))
    known = {Path(*member_path(name)).as_posix().casefold() for name in hashes}
    allowed = {name.casefold() for name in allowed_new}
    unexpected = [
        p.name
        for p in project.iterdir()
        if p.suffix.lower() in NATIVE_SUFFIXES
        and p.name.casefold() not in known | allowed
    ]
    if unexpected:
        raise ConflictError(
            "Unexpected additional native files: {}.".format(unexpected)
        )


def assert_available(project, root, name, display_name):
    names = {name.casefold(), display_name.casefold()}
    for node in root.findall("file"):
        filename = node.findtext("FileName") or ""
        leaf = Path(*member_path(filename)).stem if filename else ""
        if (
            leaf.casefold() in names
            or (node.findtext("Caption") or "").casefold() in names
        ):
            raise ConflictError(
                "Object name already exists in the project registration."
            )
    if any(path.stem.casefold() in names for path in project.iterdir()):
        raise ConflictError("Object name already exists on disk.")


class WindowsNewSTDialog:
    CATEGORY = '程序块'
    DIALOG_PROFILE = PROFILE
    LANGUAGE_VISIBLE = True
    def __init__(self, project, pid=None):
        from autoshop_bridge.windows.session import WindowsSession
        from ctypes import wintypes

        self.project = project
        self.session = WindowsSession(project, "__bridge_creation__", pid)
        self.pid = self.session.pid
        self.session.user.GetDlgCtrlID.argtypes = [wintypes.HWND]
        self.session.user.GetWindowLongW.argtypes = [wintypes.HWND, ctypes.c_int]

    def inspect(self):
        a = self.session
        if (
            not a.is_autoshop(a.pid)
            or not a.title_matches(a.text(a.main))
            or not a.text(a.main).startswith("AutoShop V4.11.0.5  ")
        ):
            raise BridgeError(
                "New-object dialog profile requires the exact verified AutoShop project/version."
            )
        if a.user.IsWindowEnabled(a.main):
            raise BridgeError(
                "Open the normal new-program dialog first; automatic menu navigation is not implemented."
            )
        trees = []
        for child in a.children(a.main):
            if a.class_name(child) != "SysTreeView32":
                continue
            parent = a.user.GetParent(child)
            while parent and parent != a.main:
                if a.text(parent) == "工程管理":
                    trees.append(child)
                    break
                parent = a.user.GetParent(parent)
        if len(trees) != 1:
            raise BridgeError(
                "Expected one project management tree for the new-program context."
            )
        try:
            call = subprocess.run(
                [
                    "powershell.exe",
                    "-NoProfile",
                    "-NonInteractive",
                    "-ExecutionPolicy",
                    "Bypass",
                    "-File",
                    str(Path(__file__).with_name("creation_context.ps1")),
                    "-Main",
                    str(a.main),
                    "-Tree",
                    str(trees[0]),
                    "-ProcessId",
                    str(a.pid),
                    "-Project",
                    str(self.project),
                ],
                capture_output=True,
                timeout=30,
                creationflags=0x08000000,
            )
            context = json.loads(call.stdout.decode("utf-8-sig"))
        except (OSError, subprocess.TimeoutExpired, ValueError) as exc:
            raise BridgeError(
                "Cannot verify the new-program tree context: {}.".format(exc)
            ) from exc
        if call.returncode or context.get("selected_name") != self.CATEGORY:
            raise BridgeError(
                "New-object dialog tree context differs from the requested category."
            )
        dialogs = []

        @a.callback_type
        def top(h, unused):
            if (
                a.window_pid(h) == a.pid
                and a.class_name(h) == "#32770"
                and a.user.IsWindowVisible(h)
                and a.user.GetParent(h) == a.main
            ):
                dialogs.append(h)
            return True

        a.user.EnumWindows(top, 0)
        if len(dialogs) != 1 or a.text(dialogs[0]) != "新建":
            raise BridgeError(
                "Expected one owned, observed new-program dialog; inspect any other prompt."
            )
        dialog = dialogs[0]
        items = [h for h in a.children(dialog) if a.user.GetDlgCtrlID(h) != -1]
        controls = {a.user.GetDlgCtrlID(h): h for h in items}
        if len(items) != len(controls) or set(controls) != {1, 2, 2816, 1247, 3022}:
            raise BridgeError(
                "New-program dialog controls differ from the observed profile."
            )
        for cid, cls, title in (
            (1, "Button", "确定"),
            (2, "Button", "取消"),
            (1247, "Static", "语言："),
            (2816, "Edit", ""),
            (3022, "ComboBox", ""),
        ):
            h = controls[cid]
            if (
                a.class_name(h) != cls
                or not a.user.IsWindowEnabled(h)
                or bool(a.user.IsWindowVisible(h)) != (
                    self.LANGUAGE_VISIBLE if cid in (1247, 3022) else True
                )
                or (title and a.text(h) != title)
            ):
                raise BridgeError("New-program dialog identity/labels changed.")
        combo = controls[3022]
        style = a.user.GetWindowLongW(combo, -16) & 0xFFFFFFFF
        if (
            not a.user.IsWindowUnicode(combo)
            or not a.user.IsWindowUnicode(controls[2816])
            or (style & 0x30 and not style & 0x200)
        ):
            raise BridgeError(
                "Unsupported new-program control encoding or owner-draw items."
            )
        count = a.window_message(combo, 0x146)
        if count != 2:
            raise BridgeError("Unsupported new-program language count.")
        choices = []
        for index in range(count):
            length = a.window_message(combo, 0x149, index)
            if length > 512:
                raise BridgeError("Unexpected new-program language length.")
            text = ctypes.create_unicode_buffer(length + 1)
            if a.window_message(combo, 0x148, index, ctypes.addressof(text)) != length:
                raise BridgeError("New-program language changed during read.")
            choices.append(text.value)
        selected = a.window_message(combo, 0x147)
        if choices != LANGUAGES or selected not in (0, 1):
            raise BridgeError("Unknown new-program language choices/selection.")
        dirty = [
            a.text(h)
            for h in a.children(a.main)
            if a.class_name(a.user.GetParent(h)) == "MDIClient"
            and a.text(h).endswith("*")
        ]
        self.dialog, self.controls = dialog, controls
        state = dict(
            project=str(self.project),
            pid=a.pid,
            dialog_hwnd=dialog,
            profile=self.DIALOG_PROFILE,
            name=a.control_text(controls[2816]),
            languages=choices,
            selected_language=choices[selected],
            category=context["selected_name"],
            dirty_documents=dirty,
        )
        return dict(state, dialog_sha256=digest_dialog(state))

    def configure(self, name):
        a = self.session
        if a.window_message(self.controls[3022], 0x147) != 1:
            a.window_message(self.controls[3022], 0x14E, 1)
            a.window_message(self.dialog, 0x111, 3022 | (1 << 16), self.controls[3022])
        text = ctypes.create_unicode_buffer(name)
        if not a.window_message(self.controls[2816], 0xC, 0, ctypes.addressof(text)):
            raise BridgeError("New-program name was rejected.")

    def submit(self):
        a = self.session
        if not a.user.PostMessageW(self.controls[1], 0xF5, 0, 0):
            raise BridgeError("New-program confirm could not be posted.")
        deadline = time.monotonic() + 6
        while a.user.IsWindow(self.dialog) and time.monotonic() < deadline:
            time.sleep(0.05)
        if a.user.IsWindow(self.dialog) or not a.user.IsWindowEnabled(a.main):
            raise BridgeError(
                "Creation left an open/unknown dialog; inspect it before retrying."
            )

    def editor(self, display_name):
        from autoshop_bridge.windows.session import connect

        return connect(self.project, display_name, self.pid, open_if_missing=True)[0]


def inspect_dialog(project, pid=None, backend=None):
    directory = select_project(project).parent
    state = (backend or WindowsNewSTDialog(directory, pid)).inspect()
    return dict(status="object_dialog", requires_open_dialog=True, **state)


def create_st(
    project,
    name,
    source_file,
    expected_dialog_sha256=None,
    pid=None,
    experimental=False,
    dry_run=False,
    backup_root=None,
    backend=None,
):
    project = select_project(project).parent
    display = validate_name(name)
    source_file = regular_file(source_file)
    source = bounded_read(source_file)
    validate_program_edit(source)
    if not source:
        raise BridgeError(
            "Provide nonempty initial ST source; blank native layout is not supported for export."
        )
    if not experimental and not dry_run:
        raise BridgeError("New ST creation requires --experimental.")
    adapter = backend or WindowsNewSTDialog(project, pid)
    before = adapter.inspect()
    if (
        before.get("profile") != PROFILE
        or before.get("category") != "程序块"
        or before.get("languages") != LANGUAGES
    ):
        raise BridgeError("Unsupported creation dialog profile/category/languages.")
    if before["dirty_documents"]:
        raise BridgeError("Save existing documents before creating a new object.")
    if not dry_run and before["dialog_sha256"] != expected_dialog_sha256:
        raise ConflictError(
            "Dialog changed or no expected dialog hash; inspect it again before creating."
        )
    state = mirror_state(project)
    assert_available(project, state["root"], name, display)
    target = project / (display + ".ST")
    plan = dict(
        project=str(project),
        input_name=name,
        actual_name=display,
        target=str(target),
        source_sha256=sha256(source),
        source_bytes=len(source),
        line_count=source.count(b"\n") + 1,
        dialog_sha256=before["dialog_sha256"],
        mirror_sha256=sha256(state["raw"]),
        matched_mirror_members=len(state["matched"]),
        direct_hcp_verified=state["direct_hcp_verified"],
        requires_open_dialog=True,
        requires_user_compile=True,
        project_atomic=False,
    )
    if dry_run:
        return dict(plan, status="object_ready")
    with target_lock(state["hcp"]):
        backup = create_backup(
            state["mirror"], state["raw"], backup_root, "create_st_project_mirror"
        )
        write_new(backup / "registration_from_mirror.hcp", state["saved_hcp"])
        write_new(backup / "initial_source.st", source)
        write_json_new(
            backup / "creation_plan.json",
            dict(
                plan,
                dialog=before,
                existing_native_hashes=state["native"],
                mirror_members=state["matched"],
            ),
        )
        stage = "before_dialog_edit"
        try:
            fresh = mirror_state(project)
            if (
                fresh["raw"] != state["raw"]
                or fresh["native"] != state["native"]
                or adapter.inspect() != before
                or source_file.read_bytes() != source
            ):
                raise ConflictError("Project, source or dialog changed during backup.")
            assert_available(project, fresh["root"], name, display)
            adapter.configure(name)
            configured = adapter.inspect()
            if (
                configured["name"] != name
                or configured["selected_language"] != LANGUAGES[1]
                or configured["dialog_hwnd"] != before["dialog_hwnd"]
                or configured["dirty_documents"]
            ):
                raise BridgeError("Configured name/language/dialog readback differs.")
            assert_old_native(project, state["native"])
            if target.exists() or state["mirror"].read_bytes() != state["raw"]:
                raise ConflictError("Project/target changed before creation.")
            write_json_new(backup / "submitted.json", configured)
            stage = "creation_submitted"
            adapter.submit()  # Never automatically retry this action.
            target = writable_target(target)
            assert_old_native(project, state["native"], (target.name,))
            editor = adapter.editor(display)
            initial = editor.read()
            if (
                initial.source
                or initial.modified
                or editor.dirty()
                or initial.read_only
            ):
                raise BridgeError(
                    "Newly created program is not the expected clean empty editor."
                )
            blank = bounded_read(target)
            source_backup = create_backup(
                target, blank, backup_root, "created_st_before_initial_source"
            )
            write_new(source_backup / "editor_before.st", b"")
            write_new(source_backup / "editor_after.st", source)
            write_json_new(
                backup / "source_backup.json", dict(backup=str(source_backup))
            )
            stage = "initial_source_edit"
            if target.read_bytes() != blank or editor.read().source or editor.dirty():
                raise ConflictError("New program changed before initial source edit.")
            editor.write(source)
            if (
                editor.read().source != source
                or not editor.dirty()
                or target.read_bytes() != blank
            ):
                raise BridgeError("Initial source write/readback differs.")
            editor.save()
            actual = parse(bounded_read(target), "st")
            if (
                actual.source != source
                or editor.read().source != source
                or editor.dirty()
            ):
                raise BridgeError("Initial source save/native verification failed.")
            assert_old_native(project, state["native"], (target.name,))
            inventory = scan(project)
            registered = [
                row
                for row in inventory["files"]
                if row.get("name") == display
                and row.get("path") == str(target)
                and row.get("kind") == "st_program"
            ]
            verified = len(registered) == 1
            result = dict(
                plan,
                status="st_created_saved"
                if verified
                else "st_created_pending_registration",
                backup=str(backup),
                source_backup=str(source_backup),
                native_sha256=sha256(target.read_bytes()),
                existing_native_files_unchanged=len(state["native"]),
                registration_verified=verified,
                registration_source=inventory["registration_source"],
                autoshop_compile_verified=False,
                requires_user_project_save=not verified,
            )
            write_json_new(backup / "creation_result.json", result)
            return result
        except (OSError, BridgeError) as exc:
            write_json_new(
                backup / "failed.json",
                dict(
                    stage=stage,
                    error=str(exc),
                    target_exists=target.exists(),
                    automatic_rollback=False,
                ),
            )
            raise BridgeError(
                "{} Creation may have changed dialog/project; do not retry blindly. "
                "Stage: {}. Backup: {}".format(exc, stage, backup)
            ) from exc
